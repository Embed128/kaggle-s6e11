def tokenize_dataset(col_order: list[str]) -> tuple[np.ndarray, np.ndarray, np.ndarray, pd.Series, int]:
    """Deterministically tokenize train and test into compact int16 arrays of shape (N, 47).
    Position 0 is reserved for target token: 0 (<Y=0>) or 1 (<Y=1>).
    """
    train_pl = pl.read_csv(DATA_RAW_DIR / "train.csv")
    test_pl = pl.read_csv(DATA_RAW_DIR / "test.csv")
    n_train = train_pl.height
    y = train_pl[TARGET_COL].to_numpy().astype(np.int8)
    test_ids = test_pl[ID_COL].to_pandas()

    raw_cols = [c for c in test_pl.columns if c != ID_COL]
    df = pl.concat([train_pl.select(raw_cols), test_pl.select(raw_cols)], how="vertical")
    del train_pl, test_pl
    gc.collect()

    N = df.height
    # Vocab layout:
    #   0: <Y=0>
    #   1: <Y=1>
    #   2..11: digits '0'..'9' (shared digit vocab; position embedding disambiguates column & place!)
    #   12..V-1: dedicated tokens per unique value of each discrete/categorical/boolean column
    next_id = 12
    token_blocks = [np.zeros((N, 1), dtype=np.int16)]  # placeholder for pos 0 (<Y>)

    for col in col_order:
        if col in CONTINUOUS_DIGIT_SPECS:
            scale, n_digits = CONTINUOUS_DIGIT_SPECS[col]
            vals = np.rint(df[col].to_numpy().astype(np.float64) * scale).astype(np.int64)
            vals = np.clip(vals, 0, 10**n_digits - 1)
            digits = np.empty((N, n_digits), dtype=np.int16)
            rem = vals
            for p in range(n_digits - 1, -1, -1):
                digits[:, p] = (rem % 10).astype(np.int16) + 2  # offset by 2
                rem //= 10
            token_blocks.append(digits)
        else:
            s = df[col].cast(pl.String).to_pandas()
            uniques = sorted(s.unique())
            mapping = {v: next_id + i for i, v in enumerate(uniques)}
            next_id += len(uniques)
            codes = s.map(mapping).to_numpy(dtype=np.int16).reshape(N, 1)
            token_blocks.append(codes)

    del df
    gc.collect()

    tokens = np.hstack(token_blocks)  # (N, 47) int16
    X_tr_tok = tokens[:n_train].copy()
    X_te_tok = tokens[n_train:].copy()
    X_tr_tok[:, 0] = y.astype(np.int16)  # set true target at position 0 for training
    X_te_tok[:, 0] = 0
    return X_tr_tok, X_te_tok, y, test_ids, next_id


if HAS_TORCH:
    class CausalBlock(nn.Module):
        def __init__(self, d_model: int, n_head: int, dropout: float = 0.1):
            super().__init__()
            assert d_model % n_head == 0
            self.n_head = n_head
            self.head_dim = d_model // n_head
            self.ln1 = nn.LayerNorm(d_model)
            self.qkv = nn.Linear(d_model, 3 * d_model, bias=False)
            self.proj = nn.Linear(d_model, d_model, bias=False)
            self.attn_drop = dropout
            self.resid_drop = nn.Dropout(dropout)

            self.ln2 = nn.LayerNorm(d_model)
            # SwiGLU-style gated FFN (stronger than plain GELU MLP at same param count)
            ffn_dim = int(d_model * 8 / 3)
            ffn_dim = ((ffn_dim + 63) // 64) * 64
            self.w12 = nn.Linear(d_model, 2 * ffn_dim, bias=False)
            self.w3 = nn.Linear(ffn_dim, d_model, bias=False)

        def forward(self, x: torch.Tensor) -> torch.Tensor:
            B, T, C = x.shape
            h = self.ln1(x)
            qkv = self.qkv(h).view(B, T, 3, self.n_head, self.head_dim)
            q, k, v = qkv.unbind(dim=2)
            q = q.transpose(1, 2)  # (B, H, T, D)
            k = k.transpose(1, 2)
            v = v.transpose(1, 2)
            attn_out = F.scaled_dot_product_attention(
                q, k, v,
                dropout_p=self.attn_drop if self.training else 0.0,
                is_causal=True,
            )
            attn_out = attn_out.transpose(1, 2).contiguous().view(B, T, C)
            x = x + self.resid_drop(self.proj(attn_out))

            h2 = self.ln2(x)
            g, u = self.w12(h2).chunk(2, dim=-1)
            x = x + self.resid_drop(self.w3(F.silu(g) * u))
            return x

    class TargetFirstTabularLM(nn.Module):
        def __init__(
            self,
            vocab_size: int,
            seq_len: int,
            d_model: int = 384,
            n_head: int = 6,
            n_layer: int = 6,
            dropout: float = 0.1,
        ):
            super().__init__()
            self.seq_len = seq_len
            self.tok_emb = nn.Embedding(vocab_size, d_model)
            self.pos_emb = nn.Embedding(seq_len, d_model)
            self.emb_drop = nn.Dropout(dropout)
            self.blocks = nn.ModuleList([CausalBlock(d_model, n_head, dropout) for _ in range(n_layer)])
            self.ln_f = nn.LayerNorm(d_model)
            self.lm_head = nn.Linear(d_model, vocab_size, bias=False)
            self.lm_head.weight = self.tok_emb.weight  # weight tying
            self.apply(self._init_weights)

        def _init_weights(self, m: nn.Module) -> None:
            if isinstance(m, nn.Linear):
                nn.init.normal_(m.weight, mean=0.0, std=0.02)
                if m.bias is not None:
                    nn.init.zeros_(m.bias)
            elif isinstance(m, nn.Embedding):
                nn.init.normal_(m.weight, mean=0.0, std=0.02)

        def forward(self, idx: torch.Tensor) -> torch.Tensor:
            B, T = idx.shape
            pos = torch.arange(T, device=idx.device).unsqueeze(0)
            x = self.emb_drop(self.tok_emb(idx) + self.pos_emb(pos))
            for blk in self.blocks:
                x = blk(x)
            return self.lm_head(self.ln_f(x))

        def seq_log_prob(self, idx: torch.Tensor) -> torch.Tensor:
            """Return exact sum_{t=1}^{T-1} log P(x_t | x_{<t}) for each row in batch -> shape (B,)."""
            logits = self.forward(idx[:, :-1])  # (B, T-1, V)
            targets = idx[:, 1:]                # (B, T-1)
            log_probs = F.log_softmax(logits.float(), dim=-1)
            tok_lp = log_probs.gather(-1, targets.unsqueeze(-1)).squeeze(-1)  # (B, T-1)
            return tok_lp.sum(dim=-1)


def predict_bayes_llr(
    model: "TargetFirstTabularLM",
    tokens: np.ndarray,
    batch_size: int,
    device: "torch.device",
    use_amp: bool,
    amp_dtype: "torch.dtype",
) -> np.ndarray:
    """Compute exact Bayes Log-Likelihood Ratio: log P(x | y=1) - log P(x | y=0)."""
    model.eval()
    N = len(tokens)
    out = np.empty(N, dtype=np.float64)
    with torch.no_grad():
        for start in range(0, N, batch_size):
            end = min(start + batch_size, N)
            bx = torch.from_numpy(tokens[start:end].astype(np.int64)).to(device, non_blocking=True)
            bx0 = bx.clone()
            bx0[:, 0] = 0
            bx1 = bx.clone()
            bx1[:, 0] = 1
            with torch.amp.autocast("cuda", enabled=use_amp, dtype=amp_dtype):
                lp0 = model.seq_log_prob(bx0)
                lp1 = model.seq_log_prob(bx1)
            out[start:end] = (lp1 - lp0).float().cpu().numpy()
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", type=str, default="fwd", choices=["fwd", "rev", "disc"])
    parser.add_argument("--n-folds", type=int, default=10)
    parser.add_argument("--tag", type=str, default="v4")
    parser.add_argument("--epochs", type=int, default=16)
    parser.add_argument("--batch-size", type=int, default=1024)
    parser.add_argument("--eval-batch-size", type=int, default=2048)
    parser.add_argument("--lr", type=float, default=1.2e-3)
    parser.add_argument("--d-model", type=int, default=384)
    parser.add_argument("--n-head", type=int, default=6)
    parser.add_argument("--n-layer", type=int, default=6)
    parser.add_argument("--dropout", type=float, default=0.10)
    parser.add_argument("--disc-weight", type=float, default=0.15, help="Bayes-BCE weight when --mode=disc")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--smoke-tokenize", action="store_true", help="Only verify tokenization shape/vocab and exit")
    args = parser.parse_args()

    ensure_dirs()
    col_order = ORDER_FWD if args.mode == "fwd" else ORDER_REV
    model_name = f"tf_lm_{args.mode}"

    t0 = time.time()
    X_tr_tok, X_te_tok, y, test_ids, vocab_size = tokenize_dataset(col_order)
    seq_len = X_tr_tok.shape[1]
    print(f"Tokenized ({model_name}): X_tr={X_tr_tok.shape}, X_te={X_te_tok.shape}, vocab={vocab_size} ({time.time()-t0:.1f}s)")
    if args.smoke_tokenize:
        print("Sample row 0 tokens:", X_tr_tok[0].tolist())
        return

    oof_path = OOF_DIR / f"oof_{args.tag}_{model_name}.npy"
    test_path = OOF_DIR / f"test_{args.tag}_{model_name}.npy"
    if not args.force and oof_path.exists() and test_path.exists():
        print(f"[SKIP] {model_name} already completed ({oof_path.name})")
        return

    if not HAS_TORCH:
        raise RuntimeError(
            "PyTorch is required! Install on RTX 5060 Ti with:\n"
            "  uv pip install torch --index-url https://download.pytorch.org/whl/cu128"
        )

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    use_amp = device.type == "cuda"
    amp_dtype = torch.bfloat16 if (use_amp and torch.cuda.is_bf16_supported()) else torch.float16
    if use_amp:
        torch.backends.cuda.matmul.allow_tf32 = True
        torch.backends.cudnn.allow_tf32 = True
        print(f"GPU: {torch.cuda.get_device_name(0)} | amp_dtype={amp_dtype}")

    ckpt_dir = OOF_DIR / f"ckpt_{args.tag}_{model_name}"
    ckpt_dir.mkdir(parents=True, exist_ok=True)

    skf = StratifiedKFold(n_splits=args.n_folds, shuffle=True, random_state=SEED)
    oof_llr = np.zeros(len(y), dtype=np.float64)
    test_llr = np.zeros(len(test_ids), dtype=np.float64)
    fold_aucs = []

    prior_logit = float(np.log(y.mean() / (1.0 - y.mean())))

    for fold, (tr_idx, va_idx) in enumerate(skf.split(X_tr_tok, y), start=1):
        f_oof_file = ckpt_dir / f"fold{fold}_oof.npy"
        f_test_file = ckpt_dir / f"fold{fold}_test.npy"

        if not args.force and f_oof_file.exists() and f_test_file.exists():
            va_pred = np.load(f_oof_file)
            te_pred = np.load(f_test_file)
            oof_llr[va_idx] = va_pred
            test_llr += te_pred / args.n_folds
            f_auc = roc_auc_score(y[va_idx], va_pred)
            fold_aucs.append(f_auc)
            print(f"  [{model_name}] Fold {fold}/{args.n_folds} [RESUMED] AUC = {f_auc:.6f}")
            continue

        ft0 = time.time()
        seed_offset = 0 if args.mode == "fwd" else (100 if args.mode == "rev" else 200)
        torch.manual_seed(SEED + seed_offset + fold)
        np.random.seed(SEED + seed_offset + fold)

        tr_tensor = torch.from_numpy(X_tr_tok[tr_idx].astype(np.int64))
        tr_loader = DataLoader(
            TensorDataset(tr_tensor),
            batch_size=args.batch_size,
            shuffle=True,
            drop_last=False,
            pin_memory=use_amp,
        )

        model = TargetFirstTabularLM(
            vocab_size=vocab_size,
            seq_len=seq_len,
            d_model=args.d_model,
            n_head=args.n_head,
            n_layer=args.n_layer,
            dropout=args.dropout,
        ).to(device)

        n_params = sum(p.numel() for p in model.parameters()) / 1e6
        if fold == 1:
            print(f"  Model params: {n_params:.2f}M | d_model={args.d_model}, n_layer={args.n_layer}, mode={args.mode}")

        optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, betas=(0.9, 0.95), weight_decay=0.05)
        total_steps = args.epochs * len(tr_loader)
        warmup_steps = max(1, int(0.08 * total_steps))

        def lr_lambda(step: int) -> float:
            if step < warmup_steps:
                return float(step + 1) / float(warmup_steps)
            prog = (step - warmup_steps) / max(1, total_steps - warmup_steps)
            return 0.05 + 0.95 * 0.5 * (1.0 + math.cos(math.pi * prog))

        scheduler = torch.optim.lr_scheduler.LambdaLR(optimizer, lr_lambda)
        scaler = torch.amp.GradScaler("cuda", enabled=(use_amp and amp_dtype == torch.float16))

        best_auc = 0.0
        best_va_llr = None
        best_state = None
        patience = 4
        no_improve = 0

        for epoch in range(1, args.epochs + 1):
            et0 = time.time()
            model.train()
            loss_sum = 0.0
            n_batches = 0

            for (bx,) in tr_loader:
                bx = bx.to(device, non_blocking=True)
                optimizer.zero_grad(set_to_none=True)

                with torch.amp.autocast("cuda", enabled=use_amp, dtype=amp_dtype):
                    logits = model(bx[:, :-1])  # (B, T-1, V)
                    targets = bx[:, 1:]
                    gen_loss = F.cross_entropy(logits.reshape(-1, vocab_size), targets.reshape(-1))

                    if args.mode == "disc":
                        # Joint Generative + Exact Bayes-LLR Discriminative Calibration!
                        bx_alt = bx.clone()
                        bx_alt[:, 0] = 1 - bx[:, 0]
                        logits_alt = model(bx_alt[:, :-1])
                        lp_true = F.log_softmax(logits.float(), dim=-1).gather(-1, targets.unsqueeze(-1)).squeeze(-1).sum(-1)
                        lp_alt = F.log_softmax(logits_alt.float(), dim=-1).gather(-1, targets.unsqueeze(-1)).squeeze(-1).sum(-1)
                        by = bx[:, 0].float()
                        # If y=1: llr = lp_true - lp_alt; if y=0: llr = lp_alt - lp_true
                        llr = torch.where(by > 0.5, lp_true - lp_alt, lp_alt - lp_true) + prior_logit
                        disc_loss = F.binary_cross_entropy_with_logits(llr, by)
                        loss = gen_loss + args.disc_weight * disc_loss
                    else:
                        loss = gen_loss

                scaler.scale(loss).backward()
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                scaler.step(optimizer)
                scaler.update()
                scheduler.step()
                loss_sum += float(loss.detach())
                n_batches += 1

            va_llr = predict_bayes_llr(model, X_tr_tok[va_idx], args.eval_batch_size, device, use_amp, amp_dtype)
            auc = roc_auc_score(y[va_idx], va_llr)
            marker = "*" if auc > best_auc + 1e-6 else ""
            print(
                f"    [{model_name}] F{fold} Ep {epoch:02d}/{args.epochs} | "
                f"loss={loss_sum/n_batches:.4f} | val_AUC={auc:.6f} {marker} ({time.time()-et0:.1f}s)",
                flush=True,
            )

            if auc > best_auc + 1e-6:
                best_auc = auc
                best_va_llr = va_llr
                best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
                no_improve = 0
            else:
                no_improve += 1
                if no_improve >= patience and epoch >= 8:
                    break

        # Predict test using best-val-AUC checkpoint
        model.load_state_dict(best_state)
        te_llr = predict_bayes_llr(model, X_te_tok, args.eval_batch_size, device, use_amp, amp_dtype)

        # Save per-fold checkpoint immediately (resumable!)
        np.save(f_oof_file, best_va_llr)
        np.save(f_test_file, te_llr)

        oof_llr[va_idx] = best_va_llr
        test_llr += te_llr / args.n_folds
        fold_aucs.append(best_auc)
        print(f"  >>> [{model_name}] Fold {fold}/{args.n_folds} BEST AUC = {best_auc:.6f} ({time.time()-ft0:.1f}s)", flush=True)

        del model, optimizer, scheduler, tr_loader, tr_tensor, best_state
        gc.collect()
        if use_amp:
            torch.cuda.empty_cache()

    # Convert LLR + prior_logit -> calibrated probabilities via sigmoid for clean blend.py compatibility!
    from scipy.special import expit
    oof_prob = expit(oof_llr + prior_logit)
    test_prob = expit(test_llr + prior_logit)
    overall_auc = roc_auc_score(y, oof_prob)

    print("\n========================================================")
    print(f"  {model_name:<12} | Mean={np.mean(fold_aucs):.6f} ± {np.std(fold_aucs):.6f} | Overall OOF={overall_auc:.6f}")
    print("========================================================")

    np.save(oof_path, oof_prob)
    np.save(test_path, test_prob)
    pd.DataFrame({ID_COL: test_ids, TARGET_COL: test_prob}).to_csv(
        SUBMISSION_DIR / f"sub_{args.tag}_{model_name}.csv", index=False
    )


if __name__ == "__main__":
    main()
