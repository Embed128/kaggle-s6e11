"""V4 Crown Jewel: Target-First Digit-Token Causal Transformer Language Model for Kaggle S6E11.

Why this breaks the 0.9520+ barrier on S6E11:
- Kaggle Playground S6E11 was generated by an autoregressive tabular LM emitting digit/value tokens.
- Standard discriminative models only receive 1 bit of supervision per row (and 98.33% are 0).
- A Target-First Causal LM serializes every row into 47 exact tokens starting with <TARGET=0/1>
  followed by exact fixed-width digit tokens for all 6 continuous columns + exact tokens for all
  18 discrete/categorical/boolean columns, receiving 46 tokens of supervision per row!
- At inference time, exact Bayes' Rule gives the log-likelihood ratio:
      LLR(x) = log P(x_1..x_46 | y=1) - log P(x_1..x_46 | y=0)

Variants supported via --mode:
  fwd  : Raw/ascending column order, pure generative NLL (early-stopped on Bayes LLR Val AUC)
  rev  : High-signal-first column order, pure generative NLL (complementary autoregressive factorization!)
  disc : High-signal-first order with Joint Generative NLL + Bayes-LLR Discriminative BCE Loss!

Engineered for RTX 5060 Ti 16GB VRAM (Blackwell BF16 + FlashAttention) & 16GB System RAM:
- Pre-tokenized 700k x 47 int16 tensor uses only ~65 MB RAM!
- Native PyTorch 2.x F.scaled_dot_product_attention(..., is_causal=True) runs blazingly fast in BF16.
- Per-fold checkpointing: safely resumes if interrupted!
"""

